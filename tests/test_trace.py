@pytest.mark.parametrize("stem", STEMS)
def test_normalized_scales_interior_area_to_one(stem: str, traced: dict) -> None:
    _, _, m = traced[stem]
    v = normalized(m, interior_area_ref(m))
    interior = m.face_areas(v)[m.face_is_interior]
    assert np.isclose(float(np.mean(interior)), 1.0, rtol=1e-12)


def test_unmodelled_argument_removes_the_cell_as_a_face() -> None:
    """A label passed as unmodelled must stop being a face, whatever else changes."""
    clean, _ = regularize(_load("demo_003_pos2"))
    base = trace_mask(clean, rim_tol=RIM_TOL)
    victim = int(base.face_labels[0])
    m = trace_mask(clean, rim_tol=RIM_TOL, unmodelled=(victim,))
    assert 0 in m.unmodelled and victim in m.unmodelled
    assert victim not in set(m.face_labels.tolist()), "an unmodelled label must not be a face"
    assert m.n_faces == base.n_faces - 1


def test_demoting_an_interior_cell_clamps_more_vertices_than_a_rim_cell() -> None:
    """Demotion costs free vertices only where the cell was NOT already against the background.

    Worth pinning because the asymmetry is easy to get wrong in both directions. A rim cell's
    vertices already touch unmodelled space, so they are already clamped and demoting it frees
    nothing new -- it can even ADD vertices, because the cell-cell edges it used to carry become
    cell-background arcs and are then subdivided to `rim_tol`. An interior cell is the opposite:
    every vertex on its outline loses its force balance.
    """
    clean, _ = regularize(_load("demo_003_pos2"))
    base = trace_mask(clean, rim_tol=RIM_TOL)

    rim_label = int(base.face_labels[~base.face_is_interior][0])
    interior_label = int(base.face_labels[base.face_is_interior][0])

    rim = trace_mask(clean, rim_tol=RIM_TOL, unmodelled=(rim_label,))
    interior = trace_mask(clean, rim_tol=RIM_TOL, unmodelled=(interior_label,))

    assert int(rim.free.sum()) == int(base.free.sum()), (
        "a rim cell's vertices are already clamped, so demoting it must not clamp more")
    assert int(interior.free.sum()) < int(base.free.sum()), (
        "demoting an interior cell must remove free vertices")


# ---------------------------------------------------------------------------------------
# 3. Why this module exists rather than `mask_analysis`
# ---------------------------------------------------------------------------------------
def test_mask_analysis_does_not_handle_a_raw_crop_but_trace_does() -> None:
    """Pin the limitation that motivates this module, so it cannot be quietly forgotten.

    `mask_analysis.find_vertices_edges_faces` assumes a padded mask in which every cell is fully
    enclosed. On a raw crop that assumption fails: it keeps a label triple only where exactly one
    2x2 window carries it, so a real trijunction spread over several windows is discarded, and the
    result does not close as a planar mesh.

    This test asserts the *contrast*, not a specific broken number: `mask_analysis` fails to close
    on this crop and `trace` closes on the same input. If someone repairs `mask_analysis` -- see
    option (i) of the `pbc_from_image` decision -- this test will fail, which is the correct
    signal: come back and delete it.
    """
    from vertax.mask_analysis import find_vertices_edges_faces

    mask = _load("demo_003_pos2")
    n_cells = int((np.unique(mask) != 0).sum())

    verts, edges, faces = find_vertices_edges_faces(mask)
    v, e, f = len(verts), len(edges), len(faces)
    euler = v - e + f
    assert euler != 0, (
        "mask_analysis now closes on a raw crop (V-E+F == 0). If that is a deliberate fix, "
        "delete this test and reconsider whether trace.py is still needed for this case.")

    clean, _ = regularize(mask)
    m = trace_mask_closed(clean, rim_tol=RIM_TOL)
    # The tracer's faces are the cells it could close; every one is a simple polygon, and it
    # accounts for essentially the whole cell population rather than a filtered subset.
    assert m.n_faces >= n_cells - 2, (
        f"tracer closed only {m.n_faces} of {n_cells} labels into faces")
    assert not m.failures, "trace_mask_closed must resolve every cell it keeps"
