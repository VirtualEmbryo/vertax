"""Regression and property tests for `vertax.trace`.

WHY THIS EXISTS. `vertax.trace` was promoted out of a local analysis script, and its correctness
was originally established by comparing it against that script on 25 crops. That comparison cannot
be repeated once the script is deleted, so the properties it checked are pinned here instead,
against a stored reference over two small committed fixtures.

THE TWO FIXTURES, and why these two. Both are real segmentation masks, deflate-compressed
(a uint16 label mask shrinks about 130x, so both together are under 32 KiB):

* `demo_003_pos2` traces cleanly -- every cell closes into a simple cycle;
* `demo_018_pos0` does not. One of its cells fails to close and is demoted to unmodelled by
  `trace_mask_closed`, which is the only fixture here that exercises that loop. Note that after a
  successful demotion `TracedMesh.failures` is *empty*, so the demotion is visible only in
  `TracedMesh.unmodelled` -- which is why that is what the reference pins.

The reference was generated by `vertax.trace` at the commit that introduced it, having been checked
to agree exactly with the pre-promotion implementation on all 25 crops. Regenerate it only with a
deliberate, explained change; a diff here means the traced geometry moved.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np
import pytest
import tifffile as tiff

from vertax.trace import (
    TracedMesh,
    interior_area_ref,
    normalized,
    regularize,
    trace_mask,
    trace_mask_closed,
    vertex_degrees,
)

HERE = Path(__file__).resolve().parent
STEMS = ["demo_003_pos2", "demo_018_pos0"]
RIM_TOL = 2.0

# sha256 of each fixture file, so a corrupted or replaced fixture is caught here rather than
# silently traced into a confusing reference mismatch further down.
FIXTURE_SHA = {
    "demo_003_pos2": "e4a9c77371b9cb038175aa305b526041f3e617168f4ed65b823dc3cae682d466",
    "demo_018_pos0": "ea59e7c0c294a12eff78824d99c6be1a9ae4973948821d9239ad23766f2400bc",
}


def _fixture_path(stem: str) -> Path:
    return HERE / f"trace_fixture_{stem}_mask.tif"


def _load(stem: str) -> np.ndarray:
    return np.asarray(tiff.imread(_fixture_path(stem)))


@pytest.fixture(scope="module")
def reference() -> dict:
    return dict(np.load(HERE / "reference_result_test_trace.npz", allow_pickle=False))


@pytest.fixture(scope="module")
def traced() -> dict[str, tuple[np.ndarray, dict, TracedMesh]]:
    """Trace both fixtures once; every test reads from this."""
    out = {}
    for stem in STEMS:
        clean, report = regularize(_load(stem))
        out[stem] = (clean, report, trace_mask_closed(clean, stem, rim_tol=RIM_TOL))
    return out


@pytest.mark.parametrize("stem", STEMS)
def test_fixture_is_readable_and_is_a_label_mask(stem: str) -> None:
    """Guard the inputs before pinning anything computed from them."""
    digest = hashlib.sha256(_fixture_path(stem).read_bytes()).hexdigest()
    assert digest == FIXTURE_SHA[stem], (
        f"fixture {stem} has changed on disk; the stored reference no longer describes it")
    m = _load(stem)
    assert m.ndim == 2
    assert m.dtype == np.uint16
    assert m.min() == 0, "a crop must contain unsegmented background, label 0"
    assert m.max() >= 10, "fixture should hold a usable number of cells"


