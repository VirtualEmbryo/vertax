@pytest.mark.parametrize("stem", STEMS)
def test_mesh_is_internally_consistent(stem: str, traced: dict) -> None:
    _, _, m = traced[stem]
    assert m.edges.min() >= 0 and m.edges.max() < m.n_verts, "edge references a missing vertex"
    assert (m.edges[:, 0] != m.edges[:, 1]).all(), "self-loop edge"
    assert len(m.vert_labels) == m.n_verts
    assert len(m.faces) == m.n_faces == len(m.face_labels)
    for f in m.faces:
        assert len(f) >= 3, "a face must be at least a triangle"
        assert len(set(f)) == len(f), "face revisits a vertex, so it is not a simple cycle"
    assert (m.face_areas() > 0).all(), "faces must be counter-clockwise with positive area"
    assert (m.edge_lengths() > 0).all()


@pytest.mark.parametrize("stem", STEMS)
def test_clamped_is_exactly_incidence_with_an_unmodelled_label(stem: str, traced: dict) -> None:
    """This is the force-balance criterion the module documents; it must be literally true."""
    _, _, m = traced[stem]
    expected = np.array([bool(s & m.unmodelled) for s in m.vert_labels])
    np.testing.assert_array_equal(m.clamped, expected)
    np.testing.assert_array_equal(m.free, ~expected)
    assert 0 in m.unmodelled, "background must always be unmodelled"


@pytest.mark.parametrize("stem", STEMS)
def test_cell_background_edges_have_both_endpoints_clamped(stem: str, traced: dict) -> None:
    """Stated as a deduced consequence in the module: check it rather than trust it."""
    _, _, m = traced[stem]
    rim = ~m.edge_is_cell_cell
    assert m.clamped[m.edges[rim]].all(), (
        "an edge touching unmodelled material must have two clamped endpoints")


@pytest.mark.parametrize("stem", STEMS)
def test_interior_faces_touch_no_rim_edge(stem: str, traced: dict) -> None:
    _, _, m = traced[stem]
    rim_labels = {int(x) for pair in m.edge_labels[~m.edge_is_cell_cell] for x in pair}
    for k, lab in enumerate(m.face_labels.tolist()):
        assert m.face_is_interior[k] == (int(lab) not in rim_labels)


def test_rim_tol_does_not_move_interior_cell_areas() -> None:
    """The module claims `rim_tol` affects clamped rim arcs ONLY. That is testable, so test it.

    If this ever fails, the documented guarantee that rim subdivision adds no information about
    the interior is false, and every interior area in the paper depends on a tolerance.
    """
    clean, _ = regularize(_load("demo_003_pos2"))
    ms = {t: trace_mask(clean, rim_tol=t) for t in (1.0, 2.0, 8.0)}
    base = ms[2.0]
    base_int = {int(l): a for l, a, i
                in zip(base.face_labels, base.face_areas(), base.face_is_interior) if i}
    assert base_int, "fixture must contain at least one interior cell"
    for t, m in ms.items():
        got = {int(l): a for l, a, i
               in zip(m.face_labels, m.face_areas(), m.face_is_interior) if i}
        assert got.keys() == base_int.keys(), f"rim_tol={t} changed which cells are interior"
        for lab, area in got.items():
            assert area == base_int[lab], f"rim_tol={t} moved interior cell {lab}'s area"


def test_rim_tol_does_change_the_rim() -> None:
    """The complement of the test above: a looser tolerance must use fewer rim vertices.

    Without this, the test above could pass trivially because `rim_tol` did nothing at all.
    """
    clean, _ = regularize(_load("demo_003_pos2"))
    tight = trace_mask(clean, rim_tol=1.0)
    loose = trace_mask(clean, rim_tol=8.0)
    assert loose.n_verts < tight.n_verts, "a looser rim tolerance must insert fewer vertices"


@pytest.mark.parametrize("stem", STEMS)
def test_regularize_is_idempotent(stem: str, traced: dict) -> None:
    """A cleaned mask has no debris left, so cleaning again must be a no-op."""
    clean, _, _ = traced[stem]
